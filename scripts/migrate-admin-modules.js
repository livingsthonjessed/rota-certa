require('dotenv').config({ path: require('node:path').join(__dirname, '..', '.env') });
const { Pool } = require('pg');
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

async function migrate() {
  await pool.query(`
    ALTER TABLE users ADD COLUMN IF NOT EXISTS cpf VARCHAR(11);
    ALTER TABLE users ADD COLUMN IF NOT EXISTS photo_data TEXT;
    CREATE UNIQUE INDEX IF NOT EXISTS users_cpf_unique ON users(cpf) WHERE cpf IS NOT NULL;

    CREATE TABLE IF NOT EXISTS customers (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      cnpj VARCHAR(14) NOT NULL UNIQUE,
      cep VARCHAR(8) NOT NULL,
      address_number TEXT NOT NULL,
      complement TEXT,
      phone TEXT NOT NULL,
      contact_name TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE TABLE IF NOT EXISTS vehicles (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      plate VARCHAR(7) NOT NULL UNIQUE,
      model TEXT NOT NULL,
      chassis TEXT NOT NULL UNIQUE,
      renavam VARCHAR(11) NOT NULL UNIQUE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS fuel_consumption NUMERIC(10,2);
    ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS axle_count INTEGER;

    CREATE TABLE IF NOT EXISTS freight_quotes (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      company_id INTEGER NOT NULL REFERENCES companies(id),
      created_by INTEGER NOT NULL REFERENCES users(id),
      vehicle_id INTEGER REFERENCES vehicles(id),
      origin TEXT NOT NULL,
      destination TEXT NOT NULL,
      vehicle_plate VARCHAR(7) NOT NULL,
      vehicle_model TEXT NOT NULL,
      distance_km NUMERIC(12,2) NOT NULL,
      duration_minutes NUMERIC(12,2) NOT NULL,
      fuel_consumption NUMERIC(10,2) NOT NULL,
      axle_count INTEGER NOT NULL,
      fuel_price NUMERIC(10,2) NOT NULL,
      estimated_liters NUMERIC(12,2) NOT NULL,
      fuel_cost NUMERIC(12,2) NOT NULL,
      has_tolls BOOLEAN NOT NULL,
      base_toll_cost NUMERIC(12,2) NOT NULL,
      toll_cost NUMERIC(12,2) NOT NULL,
      toll_estimate_available BOOLEAN NOT NULL,
      driver_payment NUMERIC(12,2) NOT NULL,
      subtotal NUMERIC(12,2) NOT NULL,
      maintenance_rate NUMERIC(5,4) NOT NULL DEFAULT 0.15,
      maintenance_cost NUMERIC(12,2) NOT NULL,
      total NUMERIC(12,2) NOT NULL,
      map_url TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      saved_at TIMESTAMPTZ
    );
    CREATE INDEX IF NOT EXISTS idx_freight_quotes_company_saved ON freight_quotes(company_id,saved_at DESC);
    CREATE INDEX IF NOT EXISTS idx_freight_quotes_destination ON freight_quotes(company_id,destination);

    ALTER TABLE trips ADD COLUMN IF NOT EXISTS mileage NUMERIC(12,2);
    ALTER TABLE trips ADD COLUMN IF NOT EXISTS freight_value NUMERIC(12,2);
    ALTER TABLE trips ADD COLUMN IF NOT EXISTS customer_id INTEGER REFERENCES customers(id);
    ALTER TABLE trips ADD COLUMN IF NOT EXISTS vehicle_id INTEGER REFERENCES vehicles(id);
    CREATE INDEX IF NOT EXISTS idx_trips_customer ON trips(customer_id);
    CREATE INDEX IF NOT EXISTS idx_trips_vehicle ON trips(vehicle_id);
    CREATE SEQUENCE IF NOT EXISTS trip_code_seq START 2000;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS latitude DOUBLE PRECISION;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS longitude DOUBLE PRECISION;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS location_accuracy DOUBLE PRECISION;
  `);
  console.log('Módulos administrativos preparados no PostgreSQL.');
}
migrate().catch(e => { console.error(e); process.exitCode=1 }).finally(() => pool.end());
