require('dotenv').config({ path: require('node:path').join(__dirname, '..', '.env') });
const { Pool } = require('pg');
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

async function migrate() {
  await pool.query(`
    ALTER TABLE users ADD COLUMN IF NOT EXISTS cpf VARCHAR(11);
    ALTER TABLE users ADD COLUMN IF NOT EXISTS photo_data TEXT;
    CREATE UNIQUE INDEX IF NOT EXISTS users_cpf_unique ON users(cpf) WHERE cpf IS NOT NULL;

    CREATE TABLE IF NOT EXISTS customers (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      cnpj VARCHAR(14) NOT NULL UNIQUE,
      cep VARCHAR(8) NOT NULL,
      address_number TEXT NOT NULL,
      complement TEXT,
      phone TEXT NOT NULL,
      contact_name TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE TABLE IF NOT EXISTS vehicles (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      plate VARCHAR(7) NOT NULL UNIQUE,
      model TEXT NOT NULL,
      chassis TEXT NOT NULL UNIQUE,
      renavam VARCHAR(11) NOT NULL UNIQUE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    ALTER TABLE trips ADD COLUMN IF NOT EXISTS mileage NUMERIC(12,2);
    ALTER TABLE trips ADD COLUMN IF NOT EXISTS freight_value NUMERIC(12,2);
    ALTER TABLE trips ADD COLUMN IF NOT EXISTS customer_id INTEGER REFERENCES customers(id);
    ALTER TABLE trips ADD COLUMN IF NOT EXISTS vehicle_id INTEGER REFERENCES vehicles(id);
    CREATE INDEX IF NOT EXISTS idx_trips_customer ON trips(customer_id);
    CREATE INDEX IF NOT EXISTS idx_trips_vehicle ON trips(vehicle_id);
    CREATE SEQUENCE IF NOT EXISTS trip_code_seq START 2000;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS latitude DOUBLE PRECISION;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS longitude DOUBLE PRECISION;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS location_accuracy DOUBLE PRECISION;
  `);
  console.log('Módulos administrativos preparados no PostgreSQL.');
}
migrate().catch(e => { console.error(e); process.exitCode=1 }).finally(() => pool.end());
