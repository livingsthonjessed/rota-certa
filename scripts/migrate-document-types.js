require('dotenv').config({quiet:true});
const {Pool}=require('pg');
const {seedDocumentTypes}=require('../document-types');

async function migrateDocumentTypes(client) {
 await client.query(`CREATE TABLE IF NOT EXISTS document_types (
  company_id INTEGER NOT NULL REFERENCES companies(id),
  name VARCHAR(30) NOT NULL,
  nature VARCHAR(6) NOT NULL CHECK (nature IN ('credit','debit')),
  PRIMARY KEY (company_id,name)
 )`);
 await client.query(`ALTER TABLE companies ADD COLUMN IF NOT EXISTS document_types_initialized BOOLEAN NOT NULL DEFAULT false;
  ALTER TABLE document_types ADD COLUMN IF NOT EXISTS id INTEGER GENERATED BY DEFAULT AS IDENTITY;
  CREATE UNIQUE INDEX IF NOT EXISTS idx_document_types_id ON document_types(id);
  CREATE UNIQUE INDEX IF NOT EXISTS idx_document_types_name ON document_types(company_id,lower(name));
  ALTER TABLE document_types ADD COLUMN IF NOT EXISTS requires_amount BOOLEAN;
  ALTER TABLE document_types ADD COLUMN IF NOT EXISTS requires_fuel BOOLEAN;
  UPDATE document_types SET requires_amount=(name<>'CTE') WHERE requires_amount IS NULL;
  UPDATE document_types SET requires_fuel=(name='Abastecimento') WHERE requires_fuel IS NULL;
  ALTER TABLE document_types ALTER COLUMN requires_amount SET DEFAULT true;
  ALTER TABLE document_types ALTER COLUMN requires_amount SET NOT NULL;
  ALTER TABLE document_types ALTER COLUMN requires_fuel SET DEFAULT false;
  ALTER TABLE document_types ALTER COLUMN requires_fuel SET NOT NULL`);
 await seedDocumentTypes(client);
 await client.query(`ALTER TABLE trip_documents DROP CONSTRAINT IF EXISTS trip_documents_document_type_check`);
 const existing=await client.query(`SELECT confupdtype FROM pg_constraint
  WHERE conrelid='trip_documents'::regclass AND conname='trip_documents_document_type_fk'`);
 if(existing.rows[0]?.confupdtype!=='c'){
 await client.query('ALTER TABLE trip_documents DROP CONSTRAINT IF EXISTS trip_documents_document_type_fk');
 await client.query(`ALTER TABLE trip_documents
  ADD CONSTRAINT trip_documents_document_type_fk FOREIGN KEY (company_id,document_type)
  REFERENCES document_types(company_id,name) ON UPDATE CASCADE`);
 }
}

async function main() {
 const pool=new Pool({connectionString:process.env.DATABASE_URL});
 const client=await pool.connect();
 try {
  await client.query('BEGIN');
  await migrateDocumentTypes(client);
  await client.query('COMMIT');
  console.log('Tipos de documento configurados.');
 } catch(error) {
  await client.query('ROLLBACK');
  throw error;
 } finally {client.release();await pool.end()}
}
if(require.main===module)main().catch(error=>{console.error(error.message);process.exitCode=1});
module.exports={migrateDocumentTypes};
